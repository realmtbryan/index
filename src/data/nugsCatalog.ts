function resolveArtworkUrl(raw?: string): string | undefined {
  if (!raw) return undefined;
  const full = raw.startsWith("http") ? raw : NUGS_IMG_BASE + raw;
  return full + "?w=640&h=360";
}

export const NUGS_CATALOG_BY_DATE: Record<string, NugsShowMetadata> = Object.fromEntries(
  Object.entries(PUBLIC_NUGS_RELEASES).map(([date, [nugsShowId, img, vod]]) => {
    const verified = VERIFIED_TRACK_DATA[date];
    const meta: NugsShowMetadata = {
      date,
      nugsShowId,
      artworkUrl: resolveArtworkUrl(img),
      hasVideoOnDemand: vod === 1,
      ...(verified ?? {}),
    };
    return [date, meta];
  })
);

export function getNugsMetadataForDate(date: string): NugsShowMetadata | undefined {
  return NUGS_CATALOG_BY_DATE[date];
}

export function getNugsReleaseUrl(nugsShowId?: string, date?: string): string {
  if (nugsShowId) {
    return "https://play.nugs.net/release/" + encodeURIComponent(nugsShowId);
  }
  if (date) {
    return "https://play.nugs.net/search?q=" + encodeURIComponent("Billy Strings " + date);
  }
  return "https://play.nugs.net/browse/artist/1125";
}
